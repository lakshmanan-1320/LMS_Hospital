-- 3. COURSE SECTIONS
-- Ordering constraint is DEFERRABLE so reorders can swap positions inside one transaction.
CREATE TABLE IF NOT EXISTS course_sections (
    section_id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    course_id UUID NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    sort_order INT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_course_sections_order UNIQUE (course_id, sort_order) DEFERRABLE INITIALLY DEFERRED,
    -- Target for the composite FK in course_lessons (guarantees lesson.course_id matches its section)
    CONSTRAINT uq_course_sections_section_course UNIQUE (section_id, course_id)
);

-- 4. COURSE LESSONS
CREATE TABLE IF NOT EXISTS course_lessons (
    lesson_id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    section_id UUID NOT NULL,
    -- Denormalized for fast per-course queries (catalogue outline, totals, progress later)
    course_id UUID NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    lesson_type VARCHAR(20) NOT NULL DEFAULT 'video'
        CHECK (lesson_type IN ('video', 'document', 'text')),
    -- Body for 'text' lessons
    content_text TEXT,
    -- Main content file: the video for 'video' lessons, the PDF/doc for 'document' lessons
    content_asset_id UUID REFERENCES media_assets(asset_id) ON DELETE SET NULL,
    duration_seconds INT NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0),
    is_preview BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_course_lessons_order UNIQUE (section_id, sort_order) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT fk_course_lessons_section_course FOREIGN KEY (section_id, course_id)
        REFERENCES course_sections(section_id, course_id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_course_lessons_course_id ON course_lessons(course_id);
CREATE INDEX IF NOT EXISTS idx_course_lessons_content_asset_id ON course_lessons(content_asset_id);

-- 5. LESSON RESOURCES (downloadable materials, stored as media_assets)
CREATE TABLE IF NOT EXISTS lesson_resources (
    resource_id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    lesson_id UUID NOT NULL REFERENCES course_lessons(lesson_id) ON DELETE CASCADE,
    asset_id UUID NOT NULL REFERENCES media_assets(asset_id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_lesson_resources_asset UNIQUE (lesson_id, asset_id)
);

CREATE INDEX IF NOT EXISTS idx_lesson_resources_asset_id ON lesson_resources(asset_id);

