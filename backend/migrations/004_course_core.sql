CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. COURSES
CREATE TABLE IF NOT EXISTS courses (
    course_id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    instructor_id UUID NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    -- Nullable while drafting; required before submit (validated in service layer)
    category_id UUID REFERENCES categories(category_id) ON DELETE RESTRICT,

    title VARCHAR(200) NOT NULL,
    slug VARCHAR(220) UNIQUE NOT NULL
        CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    subtitle VARCHAR(300),
    description TEXT,
    learning_outcomes JSONB NOT NULL DEFAULT '[]'::jsonb,
    requirements JSONB NOT NULL DEFAULT '[]'::jsonb,
    target_audience TEXT,
    level VARCHAR(20) NOT NULL DEFAULT 'all_levels'
        CHECK (level IN ('beginner', 'intermediate', 'advanced', 'all_levels')),
    language VARCHAR(50) NOT NULL DEFAULT 'English',

    is_free BOOLEAN NOT NULL DEFAULT FALSE,
    price NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
    discount_price NUMERIC(10, 2) CHECK (discount_price IS NULL OR (discount_price >= 0 AND discount_price <= price)),
    currency CHAR(3) NOT NULL DEFAULT 'INR',

    thumbnail_url VARCHAR(1024),
    -- promo_video_asset_id is added below, after media_assets exists

    status VARCHAR(20) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'pending_review', 'approved', 'rejected', 'published', 'archived')),
    rejection_reason TEXT,
    submitted_at TIMESTAMPTZ,
    reviewed_by UUID REFERENCES users(user_id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    archived_at TIMESTAMPTZ,

    -- Admin-curated highlight on the catalogue (set by Dev 1 admin screens, read by catalogue)
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,

    -- Catalogue full-text search (maintained by PostgreSQL; never written by app code)
    search_vector TSVECTOR GENERATED ALWAYS AS (
        setweight(to_tsvector('english', coalesce(title, '')), 'A') ||
        setweight(to_tsvector('english', coalesce(subtitle, '')), 'B') ||
        setweight(to_tsvector('english', coalesce(description, '')), 'C')
    ) STORED,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_courses_search_vector ON courses USING GIN (search_vector);
CREATE INDEX IF NOT EXISTS idx_courses_instructor_id ON courses(instructor_id);
CREATE INDEX IF NOT EXISTS idx_courses_category_id ON courses(category_id);
CREATE INDEX IF NOT EXISTS idx_courses_status ON courses(status);
-- Catalogue: published, not deleted, newest first
CREATE INDEX IF NOT EXISTS idx_courses_catalogue
    ON courses(published_at DESC)
    WHERE status = 'published' AND deleted_at IS NULL AND is_active = TRUE;

-- 1b. COURSE STATUS HISTORY (Course Approval audit trail)
-- One row per status transition, written in the SAME transaction as the courses.status update.
CREATE TABLE IF NOT EXISTS course_status_history (
    history_id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    course_id UUID NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,
    from_status VARCHAR(20)
        CHECK (from_status IS NULL OR from_status IN ('draft', 'pending_review', 'approved', 'rejected', 'published', 'archived')),
    to_status VARCHAR(20) NOT NULL
        CHECK (to_status IN ('draft', 'pending_review', 'approved', 'rejected', 'published', 'archived')),
    changed_by UUID REFERENCES users(user_id) ON DELETE SET NULL,
    note TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_course_status_history_course
    ON course_status_history(course_id, created_at DESC);

