-- 2. MEDIA ASSETS (Video Library & Asset Security)
-- storage_key is a PRIVATE path/key and must never be returned to clients.
-- Playback/download goes through short-lived signed URLs issued by the API.
CREATE TABLE IF NOT EXISTS media_assets (
    asset_id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    owner_id UUID REFERENCES users(user_id) ON DELETE SET NULL,
    -- Optional: asset may live in the library before being attached to a course
    course_id UUID REFERENCES courses(course_id) ON DELETE SET NULL,

    asset_type VARCHAR(20) NOT NULL
        CHECK (asset_type IN ('video', 'document', 'image')),
    title VARCHAR(255) NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(120) NOT NULL,
    file_size_bytes BIGINT NOT NULL DEFAULT 0 CHECK (file_size_bytes >= 0),
    checksum_sha256 CHAR(64),

    storage_provider VARCHAR(20) NOT NULL DEFAULT 'local'
        CHECK (storage_provider IN ('local', 's3', 'bunny', 'vimeo')),
    storage_key VARCHAR(1024) NOT NULL,
    visibility VARCHAR(20) NOT NULL DEFAULT 'private'
        CHECK (visibility IN ('private', 'preview', 'public')),
    processing_status VARCHAR(20) NOT NULL DEFAULT 'uploaded'
        CHECK (processing_status IN ('uploaded', 'processing', 'ready', 'failed')),

    duration_seconds INT CHECK (duration_seconds IS NULL OR duration_seconds >= 0),
    width INT,
    height INT,
    thumbnail_key VARCHAR(1024),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_media_assets_owner_id ON media_assets(owner_id);
CREATE INDEX IF NOT EXISTS idx_media_assets_course_id ON media_assets(course_id);
CREATE INDEX IF NOT EXISTS idx_media_assets_type_status ON media_assets(asset_type, processing_status);

-- Promo video for the catalogue detail page
